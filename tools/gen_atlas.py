#!/usr/bin/env python3
"""Generate `tools/atlas_sprites.lua` from the extracted 1.2.0 IPA.

The manifest maps every sprite name in `data_iphone/images/*.dat` to its pixel size,
which `export_gamedata.lua` uses for two jobs:

  * validating that a level object really has artwork in the 1.2.0 atlas
    (803 objects still carried stale 1.0 editor sprite ids), and
  * detecting which chapters store block sizes as half-extents (chapters 1-3) and
    which store full extents (chapters 4-5, all `LevelP2_*` files).

Usage:  python3 tools/gen_atlas.py [/var/tmp/ab120]
"""

import os
import struct
import sys

IPA_DIR = sys.argv[1] if len(sys.argv) > 1 else "/var/tmp/ab120"
IMAGES = os.path.join(IPA_DIR, "Payload/AngryBirds.app/data_iphone/images")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "atlas_sprites.lua")


def parse_dat(path):
    """`>H` texNameLen + texName, `>H` count, per sprite:
    `>H` nameLen + name, then 6 x `>h` (x, y, w, h, pivotX, pivotY)."""
    raw = open(path, "rb").read()
    pos = 0
    tex_len = struct.unpack_from(">H", raw, pos)[0]
    pos += 2 + tex_len
    count = struct.unpack_from(">H", raw, pos)[0]
    pos += 2
    out = {}
    for _ in range(count):
        name_len = struct.unpack_from(">H", raw, pos)[0]
        pos += 2
        name = raw[pos:pos + name_len].decode("latin1")
        pos += name_len
        _x, _y, w, h, _px, _py = struct.unpack_from(">6h", raw, pos)
        pos += 12
        out[name] = (w, h)
    return out


def main():
    atlas = {}
    for entry in sorted(os.listdir(IMAGES)):
        if not entry.endswith(".dat") or entry.startswith("TEXTS_"):
            continue
        try:
            atlas.update(parse_dat(os.path.join(IMAGES, entry)))
        except Exception as exc:  # fonts are not length-prefixed
            print("  skipped", entry, exc)
    with open(OUT, "w") as fh:
        fh.write("-- AUTO-GENERATED by tools/gen_atlas.py from the 1.2.0 IPA.\n")
        fh.write("-- name -> { w = width, h = height } for every sprite in the atlas.\n")
        fh.write("return {\n")
        for name in sorted(atlas):
            w, h = atlas[name]
            fh.write('  ["%s"]={w=%d,h=%d},\n' % (name, w, h))
        fh.write("}\n")
    print("wrote %s with %d sprites" % (OUT, len(atlas)))


if __name__ == "__main__":
    main()
